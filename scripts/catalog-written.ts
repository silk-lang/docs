// Writes the sidebar groups for the hand-written documentation to
// src/docs/written.ts.
//
//   pnpm catalog
//
// Each section is a folder in content/, and each page is a markdown file whose
// name starts with its position: content/book/04-ownership.md is the fourth
// chapter of the book and lives at /docs/book/ownership. The page title is the
// file's H1, except 00-overview.md, which is the section's "Overview". Every
// file is parsed here too, so markdown the site cannot render fails the run.

import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

import { parseMarkdown } from '@foldkit/markdown/vite'

import { islandAttributes } from '../src/docs/islands.ts'

const SOURCE_REPOSITORY = 'https://github.com/silk-lang/docs'

const docsRoot = resolve(import.meta.dirname, '..')

// SECTIONS

// The sidebar order of the hand-written sections. The synced standard library
// group follows them.
const sections: ReadonlyArray<Readonly<{ directory: string; title: string }>> =
  [
    { directory: 'get-started', title: 'Get started' },
    { directory: 'book', title: 'The Silk book' },
    { directory: 'reference', title: 'Language reference' },
    { directory: 'projects', title: 'Projects and packages' },
    { directory: 'tools', title: 'Tools' },
    { directory: 'guides', title: 'Guides' },
    { directory: 'appendix', title: 'Appendix' },
  ]

// PAGES

type WrittenPage = Readonly<{
  directory: string
  slug: string
  title: string
  sourcePath: string
}>

const POSITIONED_FILE = /^\d+-(.+)\.md$/

const pageTitle = (sourcePath: string, slug: string, markdown: string) => {
  if (slug === 'overview') {
    return 'Overview'
  }
  const heading = markdown.match(/^# (.+)$/m)
  if (heading === null) {
    throw new Error(`${sourcePath} has no H1 heading for its title`)
  }
  return heading[1]!.trim()
}

const sectionPages = (directory: string): ReadonlyArray<WrittenPage> =>
  readdirSync(join(docsRoot, 'content', directory))
    .filter(fileName => fileName.endsWith('.md'))
    .sort()
    .map(fileName => {
      const sourcePath = `content/${directory}/${fileName}`
      const match = fileName.match(POSITIONED_FILE)
      if (match === null) {
        throw new Error(
          `${sourcePath} does not start with its position, like 01-name.md`,
        )
      }
      const slug = match[1]!
      const markdown = readFileSync(join(docsRoot, sourcePath), 'utf8')
      try {
        parseMarkdown(markdown, { islands: islandAttributes })
      } catch (error) {
        console.error(`${sourcePath} does not parse:`)
        throw error
      }
      return {
        directory,
        slug,
        title: pageTitle(sourcePath, slug, markdown),
        sourcePath,
      }
    })

// OUTPUT

const literal = (value: string): string =>
  `'${value.replace(/['\\]/g, '\\$&')}'`

const pageEntry = (page: WrittenPage): string =>
  `      page(${literal(page.directory)}, ${literal(page.slug)}, ${literal(page.title)}, ${literal(`${SOURCE_REPOSITORY}/blob/main/${page.sourcePath}`)}),`

const writtenModule = (
  groups: ReadonlyArray<
    Readonly<{
      directory: string
      title: string
      pages: ReadonlyArray<WrittenPage>
    }>
  >,
): string => `// Generated by scripts/catalog-written.ts from content/. Do not edit by hand.

import { Option } from 'effect'

import { type DocGroup, type DocPage } from './catalog'

const page = (
  directory: string,
  slug: string,
  title: string,
  sourceUrl: string,
): DocPage => ({
  directory,
  slug,
  title,
  maybeSourceUrl: Option.some(sourceUrl),
})

export const writtenGroups: ReadonlyArray<DocGroup> = [
${groups
  .map(group =>
    [
      '  {',
      `    key: ${literal(group.directory)},`,
      `    title: ${literal(group.title)},`,
      '    showCount: true,',
      '    pages: [',
      ...group.pages.map(pageEntry),
      '    ],',
      '  },',
    ].join('\n'),
  )
  .join('\n')}
]
`

// MAIN

const main = (): void => {
  const groups = sections.map(section => ({
    ...section,
    pages: sectionPages(section.directory),
  }))

  const writtenPath = join(docsRoot, 'src/docs/written.ts')
  writeFileSync(writtenPath, writtenModule(groups))
  execFileSync('pnpm', ['exec', 'oxfmt', writtenPath], {
    cwd: docsRoot,
    stdio: 'inherit',
  })

  const pageCount = groups.reduce((sum, group) => sum + group.pages.length, 0)
  console.log(
    `cataloged ${pageCount} pages in ${groups.length} sections of content/`,
  )
}

main()
